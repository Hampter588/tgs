const {chromium,_electron:electron}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
  const credentials=fs.readFileSync('../TGS-local-admin.txt','utf8');
  const email=credentials.match(/^Email: (.+)$/m)[1],password=credentials.match(/^Password: (.+)$/m)[1];
  const browser=await chromium.launch();
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:3001');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:'Good people. Great games.'}).waitFor();
  await page.screenshot({path:'preview-online-desktop.png',fullPage:true});
  await page.locator('.sidebar').getByRole('button',{name:'Admin',exact:true}).click();
  await page.getByRole('button',{name:'Users',exact:true}).click();
  await page.locator('.admin-row').first().waitFor();
  await page.screenshot({path:'preview-admin.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.mobile-nav').getByRole('button',{name:'Feed',exact:true}).click();
  await page.screenshot({path:'preview-online-mobile.png',fullPage:true});
  await browser.close();
  const app=await electron.launch({executablePath:path.resolve('release-v0.2-final/win-unpacked/TGS.exe'),args:[]});
  const win=await app.firstWindow();
  await win.getByRole('heading',{name:'Welcome to the gathering.'}).waitFor();
  await app.close();
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('Persistent local API, administrator UI, mobile layout, and packaged Windows client verified. No browser runtime errors.');
})().catch(e=>{console.error(e.message);process.exit(1);});
